#!/usr/bin/env python3
"""
Regenerate <variant>/Dockerfile.sonicsort from upstream's generated
<variant>/Dockerfile (default variant: 17/alpine3.24).

Run after pulling an upstream docker-library/postgres update (e.g. a new
PG_VERSION) so SonicSort's patched image follows it:

    python3 sonicsort/generate.py [17/alpine3.24]

Changes from upstream, nothing else:
  1. gosu: upstream downloads tianon/gosu's prebuilt release, compiled with
     an old Go toolchain whose stdlib CVEs come along with it (4 Critical /
     32 High in SonicSort's image scan). Replaced by the same GOSU_VERSION
     built from source on a current golang image.
  2. A weekly `apk upgrade` (OS_PATCH_WEEK cache-buster), placed after the
     PostgreSQL compile layer so a weekly rebuild only re-runs that cheap
     layer.
  3. The Alpine base is overridable (ARG ALPINE_BASE, defaulting to
     upstream's alpine:<tag>): SonicSort passes sonicsort-alpine:local, its
     own Alpine assembled from Alpine's signed packages by
     poslogica/docker-alpine.

Layering on the published image instead doesn't work: the old gosu would
stay in its lower layer, and scanners still report it.
"""

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

HEADER = """\
# syntax=docker/dockerfile:1
#
# GENERATED by sonicsort/generate.py from ./Dockerfile -- do not edit;
# change the generator and re-run it instead.
#
# Patched build for SonicSort (poslogica/sonicsort): gosu rebuilt from source
# on current Go, plus a weekly Alpine security upgrade. Everything else
# (PG_VERSION, configure flags, entrypoint, postgres uid 70) is upstream's,
# so existing data volumes are unaffected. See sonicsort/generate.py.
"""

GOSU_STAGE = """\
FROM golang:1.27-alpine AS gosu
ARG GOSU_VERSION={gosu_version}
ENV CGO_ENABLED=0 GOTOOLCHAIN=local
RUN go install -trimpath -ldflags "-s -w" "github.com/tianon/gosu@${{GOSU_VERSION}}"

"""

GOSU_COPY = """\
# gosu for easy step-down from root -- built from source in the gosu stage
# above (see sonicsort/generate.py) instead of downloading the prebuilt
# release binary.
ENV GOSU_VERSION {gosu_version}
COPY --from=gosu /go/bin/gosu /usr/local/bin/gosu
RUN set -eux; \\
	gosu --version; \\
	gosu nobody true
"""

OS_PATCH = """\
# Weekly cache-buster: SonicSort's build scripts pass the current ISO week,
# so this upgrade is re-run at least weekly instead of being served from
# BuildKit's cache forever. After the compile layer, so that's all a weekly
# rebuild re-runs.
ARG OS_PATCH_WEEK=unset
RUN apk upgrade --no-cache

"""


def generate(variant: str) -> Path:
    """Write <variant>/Dockerfile.sonicsort from upstream's <variant>/Dockerfile; returns its path."""
    src = ROOT / variant / "Dockerfile"
    text = src.read_text(encoding="utf-8")

    gosu_match = re.search(r"^ENV GOSU_VERSION (\S+)$", text, re.M)
    if not gosu_match:
        sys.exit(f"{src}: no 'ENV GOSU_VERSION' -- upstream layout changed, update generate.py")
    gosu_version = gosu_match.group(1)

    # Upstream's "do not edit" banner, replaced by ours.
    text = re.sub(r"\A(#.*\n)+\n", "", text)

    # The whole "grab gosu" block: comment, ENV, and its RUN (ends at
    # "gosu nobody true").
    gosu_block = re.compile(r"^# grab gosu.*?\n\tgosu nobody true\n", re.M | re.S)
    if not gosu_block.search(text):
        sys.exit(f"{src}: gosu block not found -- upstream layout changed, update generate.py")
    text = gosu_block.sub(lambda _: GOSU_COPY.format(gosu_version=gosu_version), text, count=1)

    alpine = re.search(r"^FROM (alpine:\S+)$", text, re.M)
    if not alpine:
        sys.exit(f"{src}: no 'FROM alpine:' -- only alpine variants are supported")
    # The Alpine base becomes overridable (ALPINE_BASE, defaulting to upstream's
    # tag): SonicSort passes sonicsort-alpine:local, its own Alpine assembled by
    # poslogica/docker-alpine. The ARG has to precede the first FROM (the gosu
    # stage) to be usable in a FROM line.
    text = text.replace(f"FROM {alpine.group(1)}\n", "FROM ${ALPINE_BASE}\n", 1)
    text = re.sub(r"^(FROM \$\{ALPINE_BASE\})",
                  GOSU_STAGE.format(gosu_version=gosu_version) + r"\1", text, count=1, flags=re.M)
    text = re.sub(r"^(FROM golang:)",
                  f"ARG ALPINE_BASE={alpine.group(1)}\n\n" + r"\1", text, count=1, flags=re.M)

    anchor = "COPY docker-entrypoint.sh"
    if anchor not in text:
        sys.exit(f"{src}: '{anchor}' not found -- update generate.py")
    text = text.replace(anchor, OS_PATCH + anchor, 1)

    out = src.with_name("Dockerfile.sonicsort")
    out.write_text(HEADER + "\n" + text, encoding="utf-8", newline="\n")
    return out


if __name__ == "__main__":
    print(generate(sys.argv[1] if len(sys.argv) > 1 else "17/alpine3.24"))
